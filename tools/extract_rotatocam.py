"""Pull the ANSI grid, VGA font, palette and marquee out of rotatocam_source.html
into include/rotatocam_data.h so the firmware can replay the splash natively.

usage: python -I tools/extract_rotatocam.py tools/rotatocam_source.html include/rotatocam_data.h
"""
import base64
import json
import re
import sys


def c_bytes(name, data, per_line=24):
    out = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per_line):
        out.append("  " + ",".join(str(b) for b in data[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main(src, dst):
    html = open(src, encoding="utf8").read()
    d = json.loads(re.search(r"const D = (\{.*?\});\n", html, re.S).group(1))
    grid = base64.b64decode(d["grid"])
    font = base64.b64decode(d["font"])
    assert len(grid) == d["w"] * d["h"] * 3 and len(font) == 4096
    msg = d["msg"]
    # marquee only uses ASCII, keep it that way for the C string
    assert all(32 <= ord(ch) < 127 for ch in msg)
    tags = d["tags"]
    lines = [
        "// generated by tools/extract_rotatocam.py, do not edit",
        "// font: IBM VGA 8x16 from VileR's Ultimate Oldschool PC Font Pack (CC BY-SA 4.0)",
        "#pragma once",
        "#include <stdint.h>",
        f"#define ROTATO_W {d['w']}",
        f"#define ROTATO_H {d['h']}",
        "// tag ids used in rotato_grid[i*3+2]",
    ]
    for i, t in enumerate(tags):
        if t:
            lines.append(f"#define RTAG_{t.upper()} {i}")
    lines.append(c_bytes("rotato_grid", grid))
    lines.append(c_bytes("vga_font8x16", font, 16))
    lines.append("static const uint8_t rotato_cyc[] = {" + ",".join(map(str, d["cyc"])) + "};")
    lines.append('static const char rotato_msg[] = "' + msg.replace("\\", "\\\\").replace('"', '\\"') + '";')
    open(dst, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"wrote {dst}: grid {len(grid)} B, font {len(font)} B, msg {len(msg)} chars")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
